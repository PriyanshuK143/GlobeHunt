/**
 * Generates the simplified world map drawn inside the How-to-Play atlas.
 * Equirectangular, 360×180 units (x = lng + 180, y = 90 − lat), from Natural Earth.
 * Usage: node scripts/generate-atlas-sketch.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { feature, merge } from 'topojson-client'

const topo = JSON.parse(readFileSync('public/data/countries-110m.json', 'utf8'))
const countries = topo.objects.countries

function ringsToPath(polys, minStep = 0.9) {
  let d = ''
  for (const poly of polys) {
    for (const ring of poly.slice(0, 1)) {
      const pts = []
      for (const [lng, lat] of ring) {
        if (lat < -60) continue // drop Antarctica-ish clutter
        const x = +(lng + 180).toFixed(1)
        const y = +(90 - lat).toFixed(1)
        const last = pts[pts.length - 1]
        if (!last || Math.hypot(x - last[0], y - last[1]) >= minStep) pts.push([x, y])
      }
      if (pts.length < 4) continue
      d += 'M' + pts.map((p) => p.join(',')).join('L') + 'Z'
    }
  }
  return d
}

const land = merge(topo, countries.geometries.filter((g) => g.properties?.name !== 'Antarctica'))
const landPath = ringsToPath(land.type === 'Polygon' ? [land.coordinates] : land.coordinates)
const brazil = feature(topo, countries.geometries.find((g) => g.properties?.name === 'Brazil'))
const bg = brazil.geometry
const brazilPath = ringsToPath(bg.type === 'Polygon' ? [bg.coordinates] : bg.coordinates, 0.4)

writeFileSync(
  'src/app/howto/story/atlasSketch.ts',
  `// Generated by scripts/generate-atlas-sketch.mjs from Natural Earth (public domain).\n` +
    `// Equirectangular 360×180: x = lng + 180, y = 90 − lat.\n` +
    `export const LAND_PATH = ${JSON.stringify(landPath)}\n` +
    `export const BRAZIL_PATH = ${JSON.stringify(brazilPath)}\n`,
)
console.log('land', landPath.length, 'brazil', brazilPath.length)
